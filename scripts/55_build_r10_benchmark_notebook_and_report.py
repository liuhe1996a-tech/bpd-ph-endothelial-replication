#!/usr/bin/env python3
"""Build the executed R10 benchmark audit notebook and technical HTML report."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd


METHODS = [
    "gene_linear",
    "pca_latent",
    "vae_latent",
    "cvae_counterfactual",
    "scgen_adapted",
    "cpa_adapted",
    "sinkhorn_ot",
]


def table_html(frame: pd.DataFrame) -> str:
    return frame.to_html(index=False, border=0, classes="data-table", escape=True)


def build_notebook(root: Path, output: Path) -> None:
    bench = root / "results" / "virtual_cell_benchmark_r10"
    sensitivity = root / "results" / "virtual_cell_r10_sensitivity"

    def audit(prefix: str = "") -> pd.DataFrame:
        stem = f"{prefix}_" if prefix else "virtual_cell_"
        features = pd.read_csv(bench / f"{stem}fold_feature_manifest.tsv", sep="\t")
        splits = pd.read_csv(bench / f"{stem}grouped_validation_splits.tsv", sep="\t")
        draws = pd.read_csv(bench / f"{stem}joint_capillary_bootstrap_draws.tsv.gz", sep="\t")
        counts = features.groupby("heldout_age").agg(
            model_features=("gene", "size"), primary_hvgs=("primary_fold_hvg", "sum")
        )
        assert counts["model_features"].eq(1800).all()
        assert counts["primary_hvgs"].eq(1800).all()
        assert features["primary_fold_hvg"].astype(bool).all()
        assert splits.groupby(["heldout_age", "seed", "animal_id"])["role"].nunique().eq(1).all()
        assert draws.groupby(["heldout_age", "oxygen_group"])["bootstrap"].nunique().eq(500).all()
        return counts

    cross = pd.read_csv(bench / "cross_cohort_method_summary.tsv", sep="\t")
    summary = cross.pivot(index="method", columns="cohort", values="spearman_effect").reindex(METHODS)
    summary["rank_GSE151974"] = summary["GSE151974"].rank(ascending=False, method="min").astype(int)
    summary["rank_GSE243129"] = summary["GSE243129"].rank(ascending=False, method="min").astype(int)
    audit_json = json.loads(
        (sensitivity / "GSE243129_exact_animal_sensitivity_audit.json").read_text(encoding="utf-8")
    )
    rank_frequency = pd.read_csv(
        sensitivity / "GSE243129_all_nonempty_subset_rank_frequency.tsv", sep="\t"
    )
    assert audit_json["animals_total"] == 8
    assert audit_json["all_nonempty_subset_configurations"] == 81
    assert audit_json["unique_unordered_configurations"] == 77

    def markdown(source: str) -> dict:
        return {"cell_type": "markdown", "metadata": {}, "source": source.splitlines(keepends=True)}

    def code(source: str, output_text: str, count: int) -> dict:
        return {
            "cell_type": "code",
            "execution_count": count,
            "metadata": {},
            "outputs": [{"name": "stdout", "output_type": "stream", "text": output_text.splitlines(keepends=True)}],
            "source": source.splitlines(keepends=True),
        }

    nb = {
        "cells": [
            markdown("# R10 two-cohort perturbation-prediction benchmark audit\n\nThis output-populated audit notebook was generated by the released reporting script from the frozen result tables. It does not refit a model."),
            code("# Validate fold-only features and animal-grouped ledgers", "GSE151974\n" + audit().to_string() + "\n\nGSE243129\n" + audit("GSE243129").to_string() + "\n", 1),
            code("# Summarize primary endpoint point estimates and ranks", summary.round(4).to_string() + "\n", 2),
            code("# Audit exact GSE243129 animal-subset sensitivity", json.dumps(audit_json, indent=2) + "\n\n" + rank_frequency.to_string(index=False) + "\n", 3),
            markdown("## Interpretation boundary\n\nThe secondary cohort contains two animals in each age-by-oxygen group. Its ordering change is hypothesis-generating. Five hundred bootstrap replicates quantify resampling variability but do not increase biological replication."),
        ],
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(nb, indent=2, ensure_ascii=False), encoding="utf-8")


def build_report(root: Path, output: Path) -> None:
    bench = root / "results" / "virtual_cell_benchmark_r10"
    sensitivity = root / "results" / "virtual_cell_r10_sensitivity"
    cross = pd.read_csv(bench / "cross_cohort_method_summary.tsv", sep="\t")
    performance = (
        cross.pivot(index="method", columns="cohort", values="spearman_effect")
        .reindex(METHODS)
        .reset_index()
        .round(4)
    )
    performance["rank_GSE151974"] = performance["GSE151974"].rank(ascending=False, method="min").astype(int)
    performance["rank_GSE243129"] = performance["GSE243129"].rank(ascending=False, method="min").astype(int)
    ranks = pd.read_csv(
        sensitivity / "GSE243129_all_nonempty_subset_rank_frequency.tsv", sep="\t"
    ).round(4)
    audit = json.loads(
        (sensitivity / "GSE243129_exact_animal_sensitivity_audit.json").read_text(encoding="utf-8")
    )
    html = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>R10 perturbation-prediction benchmark technical report</title>
<style>body{{font-family:Arial,sans-serif;max-width:1080px;margin:30px auto;color:#17212b;line-height:1.5}}
h1,h2{{color:#17212b}} .box{{border-left:5px solid #4d677c;background:#f1f4f6;padding:14px 18px}}
table{{border-collapse:collapse;width:100%;font-size:12px}} th{{background:#e7e6e6}} th,td{{padding:7px;border:1px solid #b7b7b7;text-align:left}}</style></head><body>
<h1>R10 two-cohort perturbation-prediction benchmark</h1>
<p>Technical reproducibility report | 20 August 2026</p>
<div class="box"><strong>Protocol:</strong> outer-age holdout, 1,800 outer-training HVGs, animal-grouped validation, ten stochastic-model seeds and 500 shared animal bootstrap replicates within each cohort.</div>
<h2>Primary endpoint point estimates</h2>{table_html(performance)}
<h2>Exact GSE243129 subset sensitivity</h2>
<p>The cohort has {audit['animals_total']} animals, two per age-by-oxygen group. The analysis enumerates {audit['all_nonempty_subset_configurations']} non-empty subset configurations, {audit['one_pair_configurations']} one-pair configurations and {audit['leave_one_animal_configurations']} leave-one-animal configurations.</p>
{table_html(ranks)}
<div class="box"><strong>Boundary:</strong> the observed ordering change is hypothesis-generating. Bootstrap and exhaustive subset calculations quantify sensitivity of these eight animals; they do not add biological replication.</div>
<h2>Implementation boundary</h2><p>The scGen-style and CPA-style entries are transparent protocol adaptations, not executions of the official legacy packages. Sinkhorn is an explicit entropy-regularized optimal-transport baseline and is not CellOT.</p>
</body></html>"""
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(html, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    reports = root / "reports" / "r10"
    build_notebook(root, reports / "R10_virtual_cell_benchmark_audit.ipynb")
    build_report(root, reports / "R10_virtual_cell_benchmark_technical_report.html")
    print(reports)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
